export function batch5RenderedBodySelectors(channel:'whitewind'|'hackmd'|'mastodon'|'leafmill'|'clawprint'|'marked-share'|'publishmarkdown'|'render'|'dropdeploy'|'mdpage'|'opendocs'):readonly string[]{return BODY_SELECTORS[channel]}

/** Mirrors the renderer's first-unique-visible-selector rule for fixture tests. */
export function selectBatch5RenderedBody<T>(channel:'whitewind'|'hackmd'|'mastodon'|'leafmill'|'clawprint'|'marked-share'|'publishmarkdown'|'render'|'dropdeploy'|'mdpage'|'opendocs',query:(selector:string)=>readonly T[],visible:(value:T)=>boolean):T|undefined{
  for(const selector of BODY_SELECTORS[channel]){
    const matches=query(selector).filter(visible);
    if(matches.length>1)return;
    if(matches.length===1)return matches[0];
  }
}

export function batch5PublicChannel(value:string):'whitewind'|'hackmd'|'mastodon'|'leafmill'|'clawprint'|'marked-share'|'publishmarkdown'|'render'|'dropdeploy'|'mdpage'|'opendocs'|undefined {
  try{const url=new URL(value);
    if(url.protocol!=='https:'||url.username||url.password||url.port||url.search||url.hash)return;
    if(url.hostname==='opendocs.cc'&&/^\/[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\/task-[a-f0-9]{24}$/.test(url.pathname))return 'opendocs';
    if(url.hostname==='publishmarkdown.com'&&/^\/[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/.test(url.pathname))return 'publishmarkdown';
    const mdUsername=url.hostname.endsWith('.md.page')?url.hostname.slice(0,-8):'';
    if(/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(mdUsername)&&/^\/task-[a-f0-9]{24}$/.test(url.pathname))return 'mdpage';
    if(/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.onrender\.com$/.test(url.hostname)&&url.pathname==='/')return 'render';
    const dropSlug=url.hostname.endsWith('.ddploy.com')?url.hostname.slice(0,-11):'';
    if(/^[a-z0-9][a-z0-9-]{0,62}[a-z0-9]$/.test(dropSlug)&&!['app','www','api','mcp','admin','mail','cdn','static'].includes(dropSlug)&&url.pathname==='/')return 'dropdeploy';
    if(url.hostname==='whtwnd.com'&&/^\/[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?\.[a-z]{2,}\/[234567abcdefghij][234567abcdefghijklmnopqrstuvwxyz]{12}$/.test(url.pathname))return 'whitewind';
    if(url.hostname==='mastodon.social'&&/^\/@[A-Za-z0-9_]+\/[0-9]+$/.test(url.pathname))return 'mastodon';
    if(url.hostname==='hackmd.io'&&/^\/[A-Za-z0-9_-]{6,128}$/.test(url.pathname))return 'hackmd';
    if(url.hostname==='leafmill.net'&&/^\/[a-z0-9]+(?:-[a-z0-9]+)*$/.test(url.pathname))return 'leafmill';
    if((url.hostname==='markedb.in'||url.hostname==='share.markedapp.com')&&/^\/[A-Za-z0-9_-]{1,128}$/.test(url.pathname))return 'marked-share';
    if(url.hostname==='clawprint.org'&&/^\/p\/[a-z0-9]+(?:-[a-z0-9]+)*$/.test(url.pathname))return 'clawprint';
  }catch{/* Invalid URL. */}
}

