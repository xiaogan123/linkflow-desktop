export function leafmillFontFaceOnly(css:string):boolean{
  if(css.length>96_000)return false;
  const withoutComments=css.replace(/\/\*[\s\S]*?\*\//g,'');
  if(withoutComments.includes('/*'))return false;
  const blocks=[...withoutComments.matchAll(/@font-face\s*\{([^{}]*)\}/gi)];
  if(!blocks.length||withoutComments.replace(/@font-face\s*\{[^{}]*\}/gi,'').trim())return false;
  const declarations=new Set(['font-family','font-style','font-weight','font-display','font-stretch','unicode-range','src']);
  return blocks.every(block=>{
    let hasSource=false;
    for(const part of block[1].split(';')){
      if(!part.trim())continue;
      const match=/^\s*([a-z-]+)\s*:\s*([^;{}]+)\s*$/i.exec(part);
      if(!match||!declarations.has(match[1].toLowerCase())||/[!@\\]/.test(match[2]))return false;
      if(match[1].toLowerCase()!=='src'){
        if(/url\s*\(/i.test(match[2]))return false;
        continue;
      }
      const urls=[...match[2].matchAll(/url\(\s*(['"]?)([^'"\s)]+)\1\s*\)/gi)];
      if(!urls.length)return false;
      for(const item of urls){
        try{const parsed=new URL(item[2]);if(parsed.protocol!=='https:'||parsed.hostname!=='fonts.gstatic.com'||!parsed.pathname.startsWith('/s/')||parsed.username||parsed.password||parsed.port||parsed.search||parsed.hash)return false}
        catch{return false}
      }
      const remainder=match[2].replace(/url\(\s*(['"]?)([^'"\s)]+)\1\s*\)/gi,'');
      if(!/^(?:\s*format\(\s*['"]?(?:woff2|truetype)['"]?\s*\)\s*,?\s*)+$/i.test(remainder))return false;
      hasSource=true;
    }
    return hasSource;
  });
}

